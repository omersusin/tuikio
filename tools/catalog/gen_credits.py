#!/usr/bin/env python3
"""Writes the credits section of README.md from catalog/credits.json, the game manifests and
LICENSES/, so credits can't drift from what the app ships.

    python3 tools/catalog/gen_credits.py           # rewrite README.md between the markers
    python3 tools/catalog/gen_credits.py --check   # fail if README.md is out of date (CI)
"""
import glob
import json
import os
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
START = "<!-- credits:start (generated by tools/catalog/gen_credits.py) -->"
END = "<!-- credits:end -->"


def md(s):
    return str(s).replace("|", "\\|")


def license_link(file, label):
    if file and os.path.isfile(os.path.join(ROOT, "LICENSES", file)):
        return f"[{md(label)}](LICENSES/{file})"
    return md(label)


def render():
    credits = json.load(open(os.path.join(ROOT, "catalog", "credits.json"), encoding="utf-8"))
    games = [json.load(open(f, encoding="utf-8")) for f in sorted(glob.glob(os.path.join(ROOT, "catalog", "games", "*.json")))]
    games.sort(key=lambda g: g["title"].lower())
    discovery = json.load(open(os.path.join(ROOT, "catalog", "discovery.json"), encoding="utf-8"))
    out = [START, "", "## Credits", ""]

    out += ["### Made by", ""]
    for p in credits["people"]:
        who = f"**{md(p['name'])}**" + (f" ([@{p['login']}]({p['url']}))" if p.get("login") else f" ([{p['url'].removeprefix('https://')}]({p['url']}))")
        out.append(f"- {who}: {md(p['role'])}")
    out += ["", "### Community contributors", ""]
    if credits["contributors"]:
        for c in credits["contributors"]:
            out.append(f"- **{md(c['name'])}**" + (f" ([@{c['login']}](https://github.com/{c['login']}))" if c.get("login") else "") + (f": {md(c['role'])}" if c.get("role") else ""))
    else:
        out.append(f"{credits['contributors_note']} Be the first: suggest a game from the app's Create tab.")

    out += ["", f"### Games ({len(games)} playable)", "",
            "Every game is the work of its authors; Tuikio only ports and packages it. Licenses link to the full text shipped in the app.", "",
            "| Game | Authors | License | Source | Status |", "|---|---|---|---|---|"]
    for g in games:
        up = g["upstream"]
        file = "tuikio-GPL-3.0.txt" if g["origin"] == "tuikio_original" else f"{g['id']}.txt"
        out.append(f"| {md(g['title'])} | {md(', '.join(up['authors']))} | {license_link(file, up['license'])} | [{md(up['source_url'].removeprefix('https://'))}]({up['source_url']}) | {g['status']} |")

    out += ["", "### Inside the app", "", "| Component | By | License | Used for |", "|---|---|---|---|"]
    for c in credits["components"]:
        out.append(f"| [{md(c['name'])}]({c['url']}) | {md(c['by'])} | {license_link(c['license_file'], c['license'])} | {md(c['what'])} |")

    out += ["", "### Built and tested with", ""]
    for t in credits["tools"]:
        out.append(f"- [{md(t['name'])}]({t['url']}): {md(t['what'])}")

    out += ["", "### Where the catalog comes from", ""]
    for s in credits["sources"]:
        out.append(f"- [{md(s['name'])}]({s['url']}) by {md(s['by'])}")

    linked = {g["id"] for g in games}
    rest = [e for e in discovery if e.get("game_id") not in linked and e["kind"] not in ("discovery_list", "packaging_source")]
    rest.sort(key=lambda e: e["title"].lower())
    out += ["", f"### Also in the catalog ({len(rest)} links)", "",
            "Listed in the app with a link to their authors' pages; not bundled (yet). Licenses are their authors'.", ""]
    for e in rest:
        lic = e.get("upstream_license") or "UNKNOWN"
        out.append(f"- [{md(e['title'])}]({e['source_url']})" + (f" ({md(lic)})" if lic != "UNKNOWN" else ""))
    out += ["", END]
    return "\n".join(out)


def main():
    readme_path = os.path.join(ROOT, "README.md")
    readme = open(readme_path, encoding="utf-8").read()
    section = render()
    if START in readme and END in readme:
        new = readme[:readme.index(START)] + section + readme[readme.index(END) + len(END):]
    else:
        new = readme.rstrip() + "\n\n" + section + "\n"
    if "--check" in sys.argv:
        if new != readme:
            sys.exit("README.md credits are out of date: run python3 tools/catalog/gen_credits.py")
        print("README.md credits are up to date")
        return
    open(readme_path, "w", encoding="utf-8").write(new)
    print("wrote README.md credits")


if __name__ == "__main__":
    main()
