#!/usr/bin/env python3
"""Generate core/terminal/.../UnicodeWidthTable.kt from Python's unicodedata.

    python3 tools/gen_width_table.py

Wide (2 cells): East Asian Width W or F. Zero width: nonspacing/enclosing marks,
format characters (except soft hyphen), and the Hangul jamo medial/final range.
Everything else printable is one cell. Ranges are merged and emitted as sorted
IntArrays of inclusive [start, end] pairs for binary search.
"""
import os
import sys
import unicodedata

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(ROOT, "core", "terminal", "src", "main", "kotlin", "dev", "tuikio", "terminal",
                   "UnicodeWidthTable.kt")


def ranges(pred):
    out, start, prev = [], None, None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
            prev = cp
        elif start is not None:
            out.append((start, prev))
            start = None
    if start is not None:
        out.append((start, prev))
    return out


def is_zero(cp):
    if cp == 0x00AD:
        return False
    if 0x1160 <= cp <= 0x11FF or cp == 0x200B:
        return True
    cat = unicodedata.category(chr(cp))
    return cat in ("Mn", "Me", "Cf")


def is_wide(cp):
    if is_zero(cp):
        return False
    return unicodedata.east_asian_width(chr(cp)) in ("W", "F")


def emit(name, rs):
    body = []
    line = "        "
    for a, b in rs:
        item = f"0x{a:X}, 0x{b:X}, "
        if len(line) + len(item) > 100:
            body.append(line.rstrip())
            line = "        "
        line += item
    body.append(line.rstrip().rstrip(","))
    return f"    val {name} = intArrayOf(\n" + "\n".join(body) + "\n    )\n"


def main():
    zero = ranges(is_zero)
    wide = ranges(is_wide)
    src = (
        "// Generated by tools/gen_width_table.py from Unicode "
        f"{unicodedata.unidata_version}. Do not edit by hand.\n"
        "package dev.tuikio.terminal\n\n"
        "internal object UnicodeWidthTable {\n"
        + emit("ZERO", zero) + "\n" + emit("WIDE", wide) + "}\n"
    )
    with open(OUT, "w") as fh:
        fh.write(src)
    print(f"wrote {OUT}: {len(zero)} zero-width ranges, {len(wide)} wide ranges", file=sys.stderr)


if __name__ == "__main__":
    main()
