#!/usr/bin/env python3
"""Generate Tuikio brand assets (wordmark + launcher icon artwork) from editable sources.

Sources of truth:
  design/brand/mascot/*.svg           hand-authored mascot artwork (editable SVG)
  design/fonts/Unbounded-Variable.ttf wordmark typeface (SIL OFL 1.1)

Outputs (committed, regenerated by running this script):
  design/brand/wordmark/tuikio-wordmark-{ink,light}.svg
  design/brand/icons/<brand>-icon.svg          full-bleed 108x108 adaptive-icon preview
  design/brand/icons/<brand>-foreground.svg    foreground layer only (safe zone respected)

Requires: fontTools (pip install fonttools).
"""
import os
import re

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
BRAND = os.path.join(ROOT, "design", "brand")

INK = "#1E1A3A"
CORAL = "#FF6B4A"
MINT = "#2BD9A0"
SUN = "#FFC93C"


def wordmark(text="tuıkıo", weight=800, fill=INK, dot=CORAL):
    font = TTFont(os.path.join(ROOT, "design", "fonts", "Unbounded-Variable.ttf"))
    font = instancer.instantiateVariableFont(font, {"wght": weight})
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    upem = font["head"].unitsPerEm
    x_height = font["OS/2"].sxHeight
    paths, dots = [], []
    x = 0
    for ch in text:
        name = cmap[ord(ch)]
        g = glyphs[name]
        pen = SVGPathPen(glyphs)
        g.draw(TransformPen(pen, (1, 0, 0, -1, x, 0)))
        paths.append(pen.getCommands())
        if ch == "ı":
            bp = BoundsPen(glyphs)
            g.draw(bp)
            xmin, _, xmax, _ = bp.bounds
            w = xmax - xmin
            size = w * 1.08
            cx = x + (xmin + xmax) / 2
            # the "i" dots are blinking cursors: rounded cells sitting above the x-height
            dots.append((cx - size / 2, -(x_height + size * 0.42) - size, size, size * 1.18))
        x += g.width
    pad = upem * 0.04
    top = -(x_height + upem * 0.62)
    bottom = upem * 0.04
    vb = f"{-pad:.0f} {top:.0f} {x + 2 * pad:.0f} {bottom - top:.0f}"
    body = "".join(f'<path d="{d}"/>' for d in paths)
    cells = "".join(
        f'<rect x="{dx:.1f}" y="{dy:.1f}" width="{dw:.1f}" height="{dh:.1f}" rx="{dw * 0.26:.1f}"/>'
        for dx, dy, dw, dh in dots
    )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}">'
        f"<title>tuikio</title>"
        f'<g fill="{fill}">{body}</g><g fill="{dot}">{cells}</g></svg>\n'
    )


def mascot_body(name):
    src = open(os.path.join(BRAND, "mascot", name)).read()
    src = re.sub(r"<title>.*?</title>", "", src, flags=re.S)
    src = re.sub(r"<!--.*?-->", "", src, flags=re.S)
    inner = re.search(r"<svg[^>]*>(.*)</svg>", src, flags=re.S).group(1)
    # drop the ground shadow: icons get their own background
    inner = re.sub(r"<ellipse[^>]*opacity=\"0.12\"/>", "", inner)
    return inner.strip()


ICONS = {
    # brand id: (mascot file, background, ripple, scale, offset x, offset y)
    "tuikio": ("kio-hermit.svg", MINT, "#5FE6B9", 0.42, 12, 11),
    "tuikio-sun": ("kio-hermit.svg", SUN, "#FFDA73", 0.42, 12, 11),
    "blink": ("blink-cursor.svg", CORAL, "#FF8F75", 0.40, 14, 14),
    "tuitui": ("tuitui-caret-bird.svg", SUN, "#FFDA73", 0.40, 14, 13),
}


def icon(brand, foreground_only=False):
    mascot, bg, ripple, s, ox, oy = ICONS[brand]
    layers = []
    if not foreground_only:
        layers.append(f'<rect width="108" height="108" fill="{bg}"/>')
        layers.append(
            f'<circle cx="54" cy="58" r="40" fill="none" stroke="{ripple}" stroke-width="3"/>'
            f'<circle cx="54" cy="58" r="50" fill="none" stroke="{ripple}" stroke-width="2"/>'
        )
    layers.append(f'<g transform="translate({ox} {oy}) scale({s})">{mascot_body(mascot)}</g>')
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="108" height="108">'
        + "".join(layers)
        + "</svg>\n"
    )


def main():
    os.makedirs(os.path.join(BRAND, "wordmark"), exist_ok=True)
    os.makedirs(os.path.join(BRAND, "icons"), exist_ok=True)
    with open(os.path.join(BRAND, "wordmark", "tuikio-wordmark-ink.svg"), "w") as fh:
        fh.write(wordmark())
    with open(os.path.join(BRAND, "wordmark", "tuikio-wordmark-light.svg"), "w") as fh:
        fh.write(wordmark(fill="#FFFFFF"))
    for brand in ICONS:
        with open(os.path.join(BRAND, "icons", f"{brand}-icon.svg"), "w") as fh:
            fh.write(icon(brand))
        with open(os.path.join(BRAND, "icons", f"{brand}-foreground.svg"), "w") as fh:
            fh.write(icon(brand, foreground_only=True))
    print("brand assets written to", BRAND)


if __name__ == "__main__":
    main()
